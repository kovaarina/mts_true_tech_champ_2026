import sys

# путь к фиксированной локомоции (не трогай)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "common", "locomotion"))
from go2_api import Go2   # noqa: E402


def main():
    robot = Go2()                       # Go2(enable_ros2=True) — включить ROS2-мост

    while robot.step():                 # один тик симуляции; False = попытка завершена
        x, y, yaw = robot.pose()        # где я: позиция (м) и курс (рад)

        # --- сенсоры (раскомментируй и используй) ---
        # scan = robot.lidar_layer()    # 360 дальностей (м), inf = пусто — основа навигации
        # roll, pitch, yaw = robot.imu()

        # === ТВОЯ ЛОГИКА ЗДЕСЬ ===
        # Пример: держи курс на самый открытый сектор лидара, тормози у стен.
        # Пока — просто ползём вперёд (упрёмся в стену):
        robot.drive(vx=0.35, vyaw=0.0)  # vx≤0.8 м/с, vyaw≤1.5 рад/с, vy≤0.4 м/с (клипуется)

        # подсказка: аккуратная езда 0.4–0.5 м/с надёжна; резкие развороты на полной
        # скорости или удары в стену роняют робота и завершают попытку.


if __name__ == "__main__":
    main()
